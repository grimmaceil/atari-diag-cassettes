#!/usr/bin/env python3
"""Generate src/tape3/kbmap.asm: the on-screen keyboard for tape 3.

The layout is printed as five text rows; each key is a label with a space
after it, so lighting a key means inverting from its offset up to the next
space. The table maps the POKEY KBCODE (low 6 bits) to that offset
(row*40 + column, from the layout's first row), $FF for codes no key makes.
SHIFT, CONTROL and BREAK aren't KBCODEs and get their own offsets.
The arrow keys are CONTROL with - = + *, so those labels carry the arrows.
"""
from pathlib import Path

ROWS = [
    'ESC 1 2 3 4 5 6 7 8 9 0 < > BKSP',
    'TAB Q W E R T Y U I O P -↑ =↓ RET',
    'CTRL A S D F G H J K L ; +← *→ CAPS',
    'SHIFT Z X C V B N M , . / SHIFT INV',
    'SPACE  BREAK  HELP F1 F2 F3 F4',
]

# KBCODE (low 6 bits) -> label, from the OS keyboard table (Mapping the
# Atari). HELP and F1-F4 exist only on the XL (F keys: 1200XL).
KBCODES = {
    0x00: 'L', 0x01: 'J', 0x02: ';', 0x03: 'F1', 0x04: 'F2', 0x05: 'K', 0x06: '+←',
    0x07: '*→', 0x08: 'O', 0x0A: 'P', 0x0B: 'U', 0x0C: 'RET', 0x0D: 'I', 0x0E: '-↑',
    0x0F: '=↓', 0x10: 'V', 0x11: 'HELP', 0x12: 'C', 0x13: 'F3', 0x14: 'F4', 0x15: 'B',
    0x16: 'X', 0x17: 'Z', 0x18: '4', 0x1A: '3', 0x1B: '6', 0x1C: 'ESC', 0x1D: '5',
    0x1E: '2', 0x1F: '1', 0x20: ',', 0x21: 'SPACE', 0x22: '.', 0x23: 'N', 0x25: 'M',
    0x26: '/', 0x27: 'INV', 0x28: 'R', 0x2A: 'E', 0x2B: 'Y', 0x2C: 'TAB', 0x2D: 'T',
    0x2E: 'W', 0x2F: 'Q', 0x30: '9', 0x32: '0', 0x33: '7', 0x34: 'BKSP', 0x35: '8',
    0x36: '<', 0x37: '>', 0x38: 'F', 0x39: 'H', 0x3A: 'D', 0x3C: 'CAPS', 0x3D: 'G',
    0x3E: 'S', 0x3F: 'A',
}
XL_ONLY = {'HELP', 'F1', 'F2', 'F3', 'F4'}
ARROWS = {'↑': 0x5C, '↓': 0x5D, '←': 0x5E, '→': 0x5F}  # screen codes


def screen(row):
    """Internal (screen) codes of a layout row; ASCII $20-$5F is code - $20."""
    return [ARROWS[c] if c in ARROWS else ord(c) - 0x20 for c in row]


def offsets(label):
    out = []
    for r, row in enumerate(ROWS):
        words, col = row.split(' '), 0
        for w in words:
            if w == label:
                out.append(r * 40 + col)
            col += len(w) + 1
    return out


def main():
    lines = ['; Generated by tools/gen_kbmap.py: the tape 3 on-screen keyboard.', '']
    for i, row in enumerate(ROWS):
        lines.append(f'kbrow{i}\t.byte ' + ', '.join(f'${v:02X}' for v in screen(row) + [0xFF]))
    lines.append(f'KBROWS\t= {len(ROWS)}')
    table, req = [], [0] * 8
    for code in range(64):
        label = KBCODES.get(code)
        if label is None:
            table.append(0xFF)
            continue
        o = offsets(label)
        assert len(o) == 1, (label, o)
        table.append(o[0])
        if label not in XL_ONLY:
            req[code >> 3] |= 1 << (code & 7)
    lines.append('; KBCODE -> offset of its label ($FF: no key)')
    for i in range(0, 64, 16):
        lines.append('\t.byte ' + ', '.join(f'${v:02X}' for v in table[i:i + 16])
                     if i else 'kbofs\t.byte ' + ', '.join(f'${v:02X}' for v in table[i:i + 16]))
    lines.append('; KBCODEs every machine has, one bit each: what "all keys" means')
    lines.append('kbreq\t.byte ' + ', '.join(f'${v:02X}' for v in req))
    lines.append(f'KBNREQ\t= {sum(bin(v).count("1") for v in req)}')
    s1, s2 = offsets('SHIFT')
    lines += [f'KO_SHIFT1 = {s1}', f'KO_SHIFT2 = {s2}', f"KO_CTRL\t= {offsets('CTRL')[0]}",
              f"KO_BREAK = {offsets('BREAK')[0]}", '']
    out = Path(__file__).resolve().parent.parent / 'src' / 'tape3' / 'kbmap.asm'
    out.parent.mkdir(exist_ok=True)
    out.write_text('\n'.join(lines), encoding='ascii')
    print(out, 'written')


if __name__ == '__main__':
    main()
